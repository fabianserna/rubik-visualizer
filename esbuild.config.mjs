import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import fs from "fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the plugin repository.
*/
`;

const prod = process.argv[2] === "production";

/**
 * esbuild plugin to make cubing's Custom Elements idempotent when Obsidian's
 * Markdown renderer / virtual scroller detaches and re-attaches DOM nodes,
 * and safe when hot-reloading the plugin in Obsidian (even when an older VM
 * script already registered the custom elements in Chromium's C++ registry).
 */
const cubingObsidianFixPlugin = {
  name: "cubing-obsidian-fix",
  setup(build) {
    build.onLoad({ filter: /cubing[\\/]dist[\\/]lib[\\/]cubing[\\/].*\.js$/ }, async (args) => {
      let contents = await fs.promises.readFile(args.path, "utf8");

      // 1. Replace customElementsShim initialization in chunk-WELOEBCE.js with an idempotent wrapper
      if (contents.includes("customElementsShim = globalThis.customElements;")) {
        const shimReplacement = `
const __patchCubingElement = (name, clazz) => {
  if (!clazz || !clazz.prototype) return clazz;
  const proto = clazz.prototype;

  // Deduplicate adoptedStyleSheets on ManagedCustomElement
  if (name === "twisty-managed-custom-element" && typeof proto.addCSS === "function" && !proto.addCSS.__rubikPatched) {
    const origAddCSS = proto.addCSS;
    const patchedAddCSS = function(cssSource) {
      if (this.shadow && this.shadow.adoptedStyleSheets) {
        if (this.shadow.adoptedStyleSheets.includes(cssSource)) return;
      }
      return origAddCSS.call(this, cssSource);
    };
    patchedAddCSS.__rubikPatched = true;
    proto.addCSS = patchedAddCSS;
  }

  // Guard Twisty3DSceneWrapper prototype methods (works even if Blink cached an older connectedCallback in C++)
  if (name === "twisty-3d-scene-wrapper") {
    if (typeof proto.addVantage === "function" && !proto.addVantage.__rubikPatched) {
      const origAddVantage = proto.addVantage;
      const patchedAddVantage = function(vantage) {
        const isBackView = !!(vantage && vantage.options && vantage.options.backView);
        if (!isBackView && this.contentWrapper && this.contentWrapper.querySelector("twisty-3d-vantage")) {
          if (typeof this.scheduleRender === "function") this.scheduleRender();
          return;
        }
        return origAddVantage.call(this, vantage);
      };
      patchedAddVantage.__rubikPatched = true;
      proto.addVantage = patchedAddVantage;
    }
    if (typeof proto.onPuzzle === "function" && !proto.onPuzzle.__rubikPatched) {
      const origOnPuzzle = proto.onPuzzle;
      const patchedOnPuzzle = async function(inputs) {
        const key = (inputs && inputs[0] && inputs[0].id ? inputs[0].id : "") + ":" + (inputs ? inputs[1] : "");
        if (this.__rubikLastPuzzleKey === key) {
          if (typeof this.scheduleRender === "function") this.scheduleRender();
          return;
        }
        this.__rubikLastPuzzleKey = key;
        return origOnPuzzle.call(this, inputs);
      };
      patchedOnPuzzle.__rubikPatched = true;
      proto.onPuzzle = patchedOnPuzzle;
    }
  }

  // Guard TwistyButtons prototype methods (prevents >7 buttons even if C++ cached an older connectedCallback)
  if (name === "twisty-buttons") {
    if (!proto.addElement.__rubikButtonsPatched) {
      const origAddElement = proto.addElement;
      const patchedAddElement = function(element) {
        if (this.contentWrapper && this.contentWrapper.children.length >= 7) {
          if (this.__rubikSavedButtons) {
            queueMicrotask(() => {
              this.buttons = this.__rubikSavedButtons;
            });
          }
          return element;
        }
        const res = origAddElement.call(this, element);
        if (this.contentWrapper && this.contentWrapper.children.length === 7 && !this.__rubikSavedButtons) {
          queueMicrotask(() => {
            if (this.buttons && !this.__rubikSavedButtons) {
              this.__rubikSavedButtons = this.buttons;
            }
          });
        }
        return res;
      };
      patchedAddElement.__rubikButtonsPatched = true;
      proto.addElement = patchedAddElement;
    }
    if (typeof proto.update === "function" && !proto.update.__rubikPatched) {
      const origUpdate = proto.update;
      const patchedUpdate = function(buttonAppearances) {
        if (this.__rubikSavedButtons) {
          this.buttons = this.__rubikSavedButtons;
        }
        return origUpdate.call(this, buttonAppearances);
      };
      patchedUpdate.__rubikPatched = true;
      proto.update = patchedUpdate;
    }
  }

  // Guard connectedCallback before customElements.define captures it
  if (name !== "twisty-player" && typeof proto.connectedCallback === "function" && !proto.connectedCallback.__rubikPatched) {
    const origConnected = proto.connectedCallback;
    const patchedConnected = function(...cArgs) {
      if (this.__rubikConnectedOnce) {
        if (typeof this.scheduleRender === "function") {
          this.scheduleRender();
        }
        return;
      }
      this.__rubikConnectedOnce = true;
      return origConnected.apply(this, cArgs);
    };
    patchedConnected.__rubikPatched = true;
    proto.connectedCallback = patchedConnected;
  }
  return clazz;
};
customElementsShim = {
  define(name, clazz) {
    __patchCubingElement(name, clazz);
    if (!globalThis.customElements) return clazz;
    const existing = globalThis.customElements.get(name);
    if (existing) {
      __patchCubingElement(name, existing);
      return existing;
    }
    globalThis.customElements.define(name, clazz);
    return clazz;
  }
};`;
        contents = contents.replace(
          "customElementsShim = globalThis.customElements;",
          shimReplacement
        );
      }

      // 2. Reassign ClassName = customElementsShim.define("...", ClassName) so hot-reload reuses registered constructors
      contents = contents.replace(
        /customElementsShim\.define\(\s*(["'][^"']+["'])\s*,\s*([A-Za-z0-9_$]+)\s*\)/g,
        "$2 = customElementsShim.define($1, $2)"
      );

      return { contents, loader: "js" };
    });
  },
};

